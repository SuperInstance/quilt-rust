// op (d) wire-edge helpers (edge_schema_v 1), mirroring the wasm-tier
// conformance pattern (crates/quilt-core-wasm/tests/wasm_conformance.rs
// op (d)): delta is componentwise after-before, scalar imbalance is
// |after-before|, vector imbalance is the L2 norm, null prior -> null.
func wireDeltaScalar(before, after float64) float64 { return after - before }

func wireImbalanceScalar(before, after float64) float64 {
	return math.Abs(after - before)
}

func wireDeltaVector(before, after []float64) []float64 {
	out := make([]float64, len(before))
	for i := range before {
		out[i] = after[i] - before[i]
	}
	return out
}

func wireImbalanceVector(before, after []float64) float64 {
	sum := 0.0
	for i := range before {
		d := after[i] - before[i]
		sum += d * d
	}
	return math.Sqrt(sum)
}

// provenance = sha256_hex(canonical_json(inputs)); the golden inputs are
// already in canonical form (compact, ryu shortest-round-trip floats).
func provenance(canonicalInputs string) string {
	sum := sha256.Sum256([]byte(canonicalInputs))
	return hex.EncodeToString(sum[:])
}

func newGoldenEngine(t *testing.T) *Engine {
	t.Helper()
	e, err := EngineNew()
	if err != nil {
		t.Fatalf("engine_new: %v", err)
	}
	t.Cleanup(e.Free)
	if err := e.LoadSheet(sheetYAML); err != nil {
		t.Fatalf("load_sheet (golden YAML): %v", err)
	}
	return e
}

func getIs(t *testing.T, e *Engine, cell, want string) {
	t.Helper()
	got, err := e.Get(cell)
	if err != nil {
		t.Fatalf("get(%s): %v", cell, err)
	}
	if got != want {
		t.Errorf("get(%s): got %q, want %q", cell, got, want)
	}
}

func record(t *testing.T, cell, in, out string, ts uint64) string {
	t.Helper()
	seal, err := LedgerRecord(cell, in, out, ts)
	if err != nil {
		t.Fatalf("ledger_record(%s): %v", cell, err)
	}
	return seal
}

func reconcileContains(t *testing.T, cell string, needles ...string) string {
	t.Helper()
	report, err := LedgerReconcile(cell)
	if err != nil {
		t.Fatalf("ledger_reconcile(%s): %v", cell, err)
	}
	for _, n := range needles {
		if !strings.Contains(report, n) {
			t.Errorf("reconcile(%s) missing %s\n got: %s", cell, n, report)
		}
	}
	return report
}

func verifyIs(t *testing.T, cell string, want bool) {
	t.Helper()
	got, err := LedgerVerify(cell)
	if err != nil {
		t.Fatalf("ledger_verify(%s): %v", cell, err)
	}
	if got != want {
		t.Errorf("ledger_verify(%s): got %v, want %v", cell, got, want)
	}
}

func closeEnough(t *testing.T, what string, got, want float64) {
	t.Helper()
	if math.Abs(got-want) > 1e-12 {
		t.Errorf("%s: got %v, want %v", what, got, want)
	}
}

