func TestOpDEdges(t *testing.T) {
	LedgersReset()

	// -- wire edge (a la wasm conformance op (d)) ------------------------

	// scalar-bilge-edge: delta 45.0, imbalance 45.0.
	closeEnough(t, "(d) scalar delta", wireDeltaScalar(40.0, 85.0), 45.0)
	closeEnough(t, "(d) scalar imbalance", wireImbalanceScalar(40.0, 85.0), 45.0)
	if got, want := provenance("[85.0]"),
		"c488fc2a34cb70576fdb32ef7b72b0c98ee4d382813222ab518d546e7dff3d7c"; got != want {
		t.Errorf("(d) scalar provenance: got %s, want %s", got, want)
	}

	// vector-field-edge: delta [0.125,0.0625,0.125], imbalance 0.1875.
	gotDelta := wireDeltaVector(
		[]float64{0.25, -0.125, 0.5}, []float64{0.375, -0.0625, 0.625})
	wantDelta := []float64{0.125, 0.0625, 0.125}
	for i := range wantDelta {
		closeEnough(t, "(d) vector delta", gotDelta[i], wantDelta[i])
	}
	closeEnough(t, "(d) vector imbalance", wireImbalanceVector(
		[]float64{0.25, -0.125, 0.5}, []float64{0.375, -0.0625, 0.625}), 0.1875)
	if got, want := provenance("[[0.375,-0.0625,0.625]]"),
		"9a92df192679e9f0510defabf6e7431af3cc6ed8bc0dafbf49e19d7473e55224"; got != want {
		t.Errorf("(d) vector provenance: got %s, want %s", got, want)
	}

	// null-prior-first-edge: no prior -> delta null, imbalance null
	// (never fake a number). The null-prior ledger below pins the
	// imbalance-free reconcile: mean_surprise null.

	// -- the same edges through the ABI's ledger -------------------------

	// Scalar: bilge.level's own chain is reserved bit-for-bit for op (e),
	// so the golden values run on a twin cell; for scalars the ledger
	// surprise equals the wire imbalance (45.0).
	if err := LedgerInit("opd.scalar", "40.0", 1500); err != nil {
		t.Fatalf("ledger_init(opd.scalar): %v", err)
	}
	record(t, "opd.scalar", "85.0", "85.0", 2000)
	verifyIs(t, "opd.scalar", true)
	reconcileContains(t, "opd.scalar",
		`"entries":1`, `"total_surprise":45.0`, `"mean_surprise":45.0`,
		`"chain_intact":true`, `"balanced":true`)

	// Vector: the ABI takes uint64 millis, so the golden ts 3000.5
	// truncates to 3000; delta/imbalance are value-derived. The ledger's
	// own entry imbalance is a distance, not the wire L2 norm (that is
	// not exposed by the C ABI), so only integrity is pinned here.
	if err := LedgerInit("room.field", "[0.25,-0.125,0.5]", 2500); err != nil {
		t.Fatalf("ledger_init(room.field): %v", err)
	}
	record(t, "room.field", "[0.375,-0.0625,0.625]", "[0.375,-0.0625,0.625]", 3000)
	verifyIs(t, "room.field", true)
	reconcileContains(t, "room.field",
		`"entries":1`, `"chain_intact":true`, `"continuity_intact":true`,
		`"balanced":true`)

	// Null-prior: record without init creates the ledger without a
	// genesis, so the first edge carries no imbalance (mean_surprise
	// null), matching golden delta/imbalance null.
	record(t, "fresh.sensor", "7.0", "7.0", 5000)
	verifyIs(t, "fresh.sensor", true)
	reconcileContains(t, "fresh.sensor",
		`"entries":1`, `"mean_surprise":null`, `"open_inputs":0`,
		`"chain_intact":true`, `"balanced":true`)
	if got, want := provenance("[7.0]"),
		"e8980b1b4ea755da488add3544bf1c538901b74c0551a58de69a199baa5c4aeb"; got != want {
		t.Errorf("(d) null-prior provenance: got %s, want %s", got, want)
	}
}

func TestOpELedgerChain(t *testing.T) {
	LedgersReset()

	if err := LedgerInit("bilge.level", "40.0", 1000); err != nil {
		t.Fatalf("ledger_init genesis 40.0 @1000: %v", err)
	}
	if err := LedgerInit("bilge.level", "40.0", 1000); err == nil {
		t.Error("double ledger_init must be rejected")
	}

	root, err := LedgerChainHash("bilge.level")
	if err != nil {
		t.Fatalf("chain_hash (genesis root): %v", err)
	}
	if root != gGenesisRoot {
		t.Errorf("genesis root: got %s, want %s", root, gGenesisRoot)
	}

	for i, rec := range []struct {
		seal string
		val  string
		ts   uint64
	}{
		{gEntry1, "85.0", 2000},
		{gEntry2, "87.5", 3000},
		{gEntry3, "87.5", 4000},
	} {
		if got := record(t, "bilge.level", rec.val, rec.val, rec.ts); got != rec.seal {
			t.Errorf("seal %d bit-for-bit: got %s, want %s", i+1, got, rec.seal)
		}
	}

	verifyIs(t, "bilge.level", true)
	if _, err := LedgerVerify("no.such.cell"); err == nil {
		t.Error("unknown ledger must return an error (-1)")
	}

	head, err := LedgerChainHash("bilge.level")
	if err != nil {
		t.Fatalf("chain_hash: %v", err)
	}
	if head != gChainHash {
		t.Errorf("chain_hash: got %s, want %s", head, gChainHash)
	}
	t.Logf("chain_hash = %s", head)

	reconcileContains(t, "bilge.level", gReconcileNeedles...)
}

func TestErrorDiscipline(t *testing.T) {
	e := newGoldenEngine(t)

	if _, err := e.Get("no.such.cell"); err == nil {
		t.Error("unknown cell must return an error")
	} else if err.Error() == "" {
		t.Error("error must carry last_error detail")
	}

	var nilEngine *Engine
	if _, err := nilEngine.Get("x"); err == nil {
		t.Error("nil engine must be tolerated as an error, not a crash")
	}

	if _, err := LedgerRecord("bad.json.cell", "{not json", "1", 1); err == nil {
		t.Error("bad JSON input must return an error")
	}

	if _, err := e.Get("status"); err != nil {
		t.Fatalf("get(status) after failures: %v", err)
	}

	// The library's last_error keeps stale bytes after a successful
	// clear (verified against the C ABI directly with a C probe), so
	// ""-after-success is not assertable here; the C smoke test makes
	// the same omission.

	nilEngine.Free()
}
