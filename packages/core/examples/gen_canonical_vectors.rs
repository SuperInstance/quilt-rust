//! Regenerate `compat/canonical-vectors.json` FROM THE NORMATIVE PORT.
//!
//! Run:
//!   cargo run -p quilt-core --example gen_canonical_vectors
//!
//! WHY THIS IS AN EXAMPLE RATHER THAN A SCRIPT IN THE PYTHON TIER:
//! every `canonical` string below is produced by calling
//! `quilt_core::ledger::canonical_json` — the *Rust* function, the one
//! `docs/cell-ledger.md` §4 pins ("floats as Rust's shortest-round-trip
//! decimal (serde_json / ryū semantics)"). Nothing in this file
//! re-implements the rule, so the oracle cannot drift from the port it
//! claims to certify.
//!
//! The previous revision of this file was generated by
//! `bindings/python/quilt/ledger.py`. That was wrong on principle and
//! wrong in fact — see the `note` field it emits.
//!
//! Deterministic: every field is either a constant or a product of
//! `canonical_json` + `sha256::hex`, and the `at` stamp is pinned, so
//! re-running the generator on an unchanged port is a no-op diff.

use quilt_core::ledger::{canonical_json, sha256};
use serde::Serialize;
use serde_json::{json, Value};

/// One vector. Field ORDER is the order serde emits for a struct, which
/// is what keeps the file's shape stable across regenerations.
#[derive(Serialize)]
struct Case {
    name: &'static str,
    value: Value,
    canonical: String,
    sha256: String,
}

#[derive(Serialize)]
struct Doc {
    at: &'static str,
    spec: &'static str,
    purpose: &'static str,
    generated_by: &'static str,
    note: &'static str,
    case_count: usize,
    cases: Vec<Case>,
}

const PURPOSE: &str = "\
THE SHARED ARTEFACT FOR THE 'ONE KERNEL, MANY LANGUAGES' CLAIM.

docs/cell-ledger.md says 'every quilt tier (Rust, TS, Go) produces byte-identical
preimages from the same data', and that a port 'reproduces the same chain hashes
from the same entries'. The Rust and Python tiers SHARE a golden
(compat/golden.json) and are genuinely differential-tested -- bindings/python/
tests/test_compat.py PASSES and reproduces the Rust golden's three sealed hashes
and its chain_hash. The Go tier has its OWN golden: a different spec
(quilt-go-golden/1), a different sheet, and a DIFFERENT chain envelope
(sha256_hex(chain_prev + ':' + provenance)). So the claim is ASSERTED for Go, not
checked. And the TypeScript tier the spec names DOES NOT EXIST -- quilt-rust has
two .ts files and both are demo sheets.

THE CANONICAL FORM IS THE THING ALL THE TIERS MUST AGREE ON, AND IT IS SMALL
AND CHECKABLE. So it gets its own vector file: the input, the exact expected
canonical bytes, and the sha256 of those bytes.

A port conforms by reproducing every `canonical` string here. That is a
one-line check per port, and it needs no engine, no sheet and no chain.";

const GENERATED_BY: &str = "\
packages/core/examples/gen_canonical_vectors.rs -- THE RUST TIER, WHICH IS THE
NORMATIVE PORT. Every `canonical` below is the return value of
quilt_core::ledger::canonical_json(), the function docs/cell-ledger.md SS4 pins
and that every other tier is measured against.

IT WAS PREVIOUSLY GENERATED BY THE PYTHON TIER (bindings/python/quilt/ledger.py).
That was the defect this regeneration exists to repair. The Python tier is
byte-equivalent to the Rust golden on that golden's OWN samples -- 40.0, 85.0,
87.5, 1000.0, 2000.0 -- and never on the whole domain: it disagrees with the
Rust on every float in the band |v| in [1e-5, 1e-4). A conformance suite
generated by its own author proves only that the author can agree with itself.

Regenerate with:  cargo run -p quilt-core --example gen_canonical_vectors";

const NOTE: &str = "\
THE FLOAT-RULE BOUNDARY IS THE POINT OF THIS FILE, AND IT IS NOW PINNED BY
BOUNDARIES, NOT BY SAMPLES.

Write kk = floor(log10(|v|)) + 1, so that 10^(kk-1) <= |v| < 10^kk. Each port
picks plain-decimal vs exponent form as a function of kk, and the three rules
DO NOT AGREE:

  RUST  (serde_json / ryu, NORMATIVE)  exponent iff kk <= -5 or kk >= 17
  PYTHON (repr)                        exponent iff kk <= -4 or kk >= 17
  GO     (strconv 'g', prec -1)        exponent iff kk <= -4 or kk >=  7

THREE divergence classes follow, and the cases below cover BOTH SIDES of every
boundary so a one-band change in any port turns its own test red:

  * kk == -4, i.e. |v| in [1e-5, 1e-4): the RUST writes plain decimals
    (1e-5 -> 0.00001) and the other two write exponents (1e-5). Python and Go
    BOTH diverge here. Python's repr switches to exponent form one decade
    earlier than ryu on the low side and nowhere else.
  * 7 <= kk <= 16, i.e. |v| in [1e6, 1e17): the Go port's 'g' format picks
    exponent form at six significant digits, so it writes 1e6, 3.333333333333333e8
    and 1e15 where the RUST writes 1000000.0, 333333333.3333333 and
    1000000000000000.0. This band contains every ordinary large number, which is
    why the Go tier went unnoticed: its golden sheet happens to hold none.
  * the exponent SIGN, everywhere. ryū always writes it: 1e+16, 1e+100,
    1.7976931348623157e+308. Both other ports stripped the '+', giving 1e16 and
    1e100. This is the class that made the RUST fail its OWN vector file on the
    first run, because the file had been generated by the Python port and
    recorded the Python's spelling as if it were the normative one. It affects
    every value at or above 1e16, including the two cases the first revision of
    this file already contained.

The int/float hazard remains the one docs/cell-ledger.md names by name --
'JavaScript renders 40.0 as 40; ports must preserve float-vs-int distinction to
stay on-chain.' ECMAScript's JSON.stringify is therefore NOT the rule. The rule
is ryu/serde_json semantics, and a port that borrows JSON.stringify will pass
every ordinary case and fail exactly the ones that matter.";

fn main() {
    // `json!` is used throughout rather than `Value::from(vec![..])`: the
    // latter cannot infer which `Vec<T> -> Value` impl is meant, and
    // `json!` also keeps the literal int-vs-float distinction visible in
    // the source, which is the whole subject of this file.
    let cases: Vec<(&'static str, Value)> = vec![
        // -- structure, ordering, escaping (carried over from the first revision)
        ("int renders as an int", json!(40)),
        (
            "float renders with its marker (the spec's named hazard)",
            json!(40.0),
        ),
        ("int and float are NOT the same value", json!([40, 40.0])),
        ("negative zero", json!(-0.0)),
        ("zero", json!(0.0)),
        (
            "the low exponent-form boundary: kk = -5, still an exponent",
            json!(1e-6),
        ),
        ("a float well inside the exponent form", json!(1e-7)),
        ("the high exponent-form boundary: kk = 17", json!(1e16)),
        ("a large float, kk = 22", json!(1e21)),
        (
            "a shortest-round-trip float with 16 significant digits",
            json!(333333333.3333333),
        ),
        ("a negative float", json!(-1.5)),
        (
            "keys sorted, not insertion order",
            json!({"b": 1, "a": 2, "C": 3}),
        ),
        (
            "the astral-plane keys (UTF-8 byte order)",
            json!({"\u{10000}": "A", "\u{E000}": "B"}),
        ),
        (
            "nested objects sort at every level",
            json!({"z": {"y": 1, "x": 2}, "a": [3, {"q": 1, "p": 2}]}),
        ),
        ("null, true and false", json!([null, true, false])),
        ("an empty object and an empty array", json!([{}, []])),
        (
            "strings escape the standard way",
            json!(["quote\" back\\ tab\t newline\n"]),
        ),
        (
            "non-ASCII is NOT escaped",
            json!("caf\u{e9} \u{4e2d}\u{6587}"),
        ),
        ("a big integer stays exact", json!(9007199254740993u64)),
        (
            "a big integer and its float neighbour are different values",
            json!([9007199254740993u64, 9007199254740992.0]),
        ),
        (
            "deep nesting",
            json!({"a": {"b": {"c": {"d": [1, 2, {"e": 3.5}]}}}}),
        ),
        // -- DIVERGENCE CLASS 1: kk == -4, i.e. |v| in [1e-5, 1e-4).
        //    The RUST writes plain decimals there; Python and Go write
        //    exponents. The band is exactly one decade wide and the old
        //    vector set sat entirely OUTSIDE it, which is why the Python
        //    tier passed a file it had generated itself.
        (
            "BOUNDARY kk=-4: the Rust's plain-decimal band starts at 1e-5",
            json!(1e-5),
        ),
        ("kk=-4 with a fractional mantissa", json!(1.2e-5)),
        (
            "kk=-4 at the top of the band, just under 1e-4",
            json!(9.999999e-5),
        ),
        (
            "kk=-4, negative, in an array with its int neighbour",
            json!([-1e-5, 0]),
        ),
        // -- The two neighbours of that band, which must NOT diverge. A
        //    rule that is off by one decade in EITHER direction goes red here.
        (
            "ONE STEP BELOW the kk=-4 band: all three ports agree (exponent)",
            json!(9.99999e-6),
        ),
        (
            "ONE STEP ABOVE the kk=-4 band: all three ports agree (plain)",
            json!(1e-4),
        ),
        // -- DIVERGENCE CLASS 2: 7 <= kk <= 16, i.e. |v| in [1e6, 1e17).
        //    The Go port's 'g' format cuts to exponents at six significant
        //    digits, so it writes 1e6 where the RUST writes 1000000.0. This
        //    band holds every ordinary large number.
        (
            "kk=6: the last plain-decimal step, all three ports agree",
            json!(999999.0),
        ),
        (
            "kk=7: the Go port's cutover, the Rust still writes it in full",
            json!(1000000.0),
        ),
        ("kk=7 with a fractional part", json!(9999999.0)),
        ("kk=7 at the bottom of the band", json!(1.5e6)),
        (
            "kk=16: the last plain-decimal step before the exponent band",
            json!(1e15),
        ),
        (
            "kk=16, the exact 2^53 float beside its (different) int neighbour",
            json!([9007199254740993u64, 9007199254740992.0]),
        ),
        (
            "ONE STEP ABOVE the kk=16 band: all three ports agree (exponent)",
            json!(1e17),
        ),
        (
            "the whole float band in one value, so ordering is visible",
            json!([1e-5, 1e-4, 999999.0, 1000000.0, 1e15, 1e16]),
        ),
        // -- DIVERGENCE CLASS 3: the exponent SPELLING. The RUST (ryu)
        //    always signs the exponent -- 1e+16, not 1e16. Both other
        //    ports stripped the '+', which is what made the Rust fail its
        //    own vectors on the very first run.
        (
            "the signed exponent inside a structure, where a port that forgot it cannot hide",
            json!([1e16, 1e17, 1e21]),
        ),
        ("the high band at kk = 100", json!(1e100)),
        // -- extremes: the rule must hold at both ends of f64
        ("the smallest positive subnormal", json!(5e-324)),
        ("the largest finite f64", json!(1.7976931348623157e308)),
        (
            "ordinary decimals, for the record",
            json!([0.1, 0.3, 1.0, 1000.0]),
        ),
    ];

    let built: Vec<Case> = cases
        .into_iter()
        .map(|(name, value)| {
            // THE NORMATIVE CALL. Nothing else decides what a canonical string is.
            let canonical = canonical_json(&value);
            let digest = sha256::hex(canonical.as_bytes());
            Case {
                name,
                value,
                canonical,
                sha256: digest,
            }
        })
        .collect();

    let doc = Doc {
        at: "2026-10-19",
        spec: "quilt-canonical-vectors/1",
        purpose: PURPOSE,
        generated_by: GENERATED_BY,
        note: NOTE,
        case_count: built.len(),
        cases: built,
    };

    // One-space indent, matching the file's existing shape, so a
    // regeneration diff shows CHANGES and not reflow.
    let mut out: Vec<u8> = Vec::new();
    let formatter = serde_json::ser::PrettyFormatter::with_indent(b" ");
    let mut ser = serde_json::Serializer::with_formatter(&mut out, formatter);
    serde::Serialize::serialize(&doc, &mut ser).expect("serializing plain data is infallible");
    out.push(b'\n');

    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../compat/canonical-vectors.json");
    std::fs::write(&path, &out).expect("the vector file must be writable");

    eprintln!(
        "wrote {} ({} cases) from the RUST port",
        path.display(),
        doc.case_count
    );
}
